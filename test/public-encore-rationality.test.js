'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {policyStatusScore}=require('../tactics');
const {evaluateMoveV3}=require('../field-counterplay');
const {Bot,load}=require('../lab');
const {reportedLive}=require('../reported-live-roster-20261027');
const {groups}=require('../environment-m7-teams');
const {makeThreeBattle}=require('../engine-three-branch');

const context={ratio:0.9,turn:3,foeHP:0.8,
 foeLastMove:'Swords Dance',foeLastMoveTurn:2,
 boosts:{},foeBoosts:{atk:2},lastStatuses:{},hazards:{}};

test('Encore is sensible when publicly observed opposing setup has not been encored',()=>{
 const free=policyStatusScore('Encore',context);
 assert.ok(free>100,'Before Encore volatile, legitimate repeat-setup threat can be encored');
 assert.equal(policyStatusScore('Encore',{...context,foeEncoreActive:true}),0,
  'After public Encore active, prevent a pointless repeat attempt');
});

test('opt-in v4 penalizes an already active Encore, retaining an attacking alternative',()=>{
 const sim=load(),dex=sim.Dex.mod('champions');
 const pri=reportedLive().find(x=>x.species==='Primarina');
 assert.equal(evaluateMoveV3(dex,pri,'Golisopod','Encore',
  {...context,foeEncoreActive:true,available:pri.moves}),0);
 assert.ok(evaluateMoveV3(dex,pri,'Golisopod','Sparkling Aria',
  {...context,foeEncoreActive:true,available:pri.moves})>0);
 assert.ok(evaluateMoveV3(dex,pri,'Golisopod','Encore',
  {...context,foeEncoreActive:false,available:pri.moves})>0);
});

test('real pinned Showdown Encore public event toggles ONLY v4 status tracking',async()=>{
 const sim=load();
 const own=reportedLive(),foe=groups.find(x=>x.name==='01_M7_golisopod_balance').team;
 const b=makeThreeBattle(sim,own,foe,{
  ownThree:['Primarina','Metagross','Hydreigon'],
  foeThree:['Golisopod','Mimikyu','Garchomp'],
  seed:[2026,10,29,55]
 });
 let logs,capturedRequest;
 try{
  const enc=b.p1.active[0].moveSlots.findIndex(x=>x.id==='encore');
  const b1=b.p2.active[0].moveSlots.findIndex(x=>x.id==='swordsdance');
  assert.ok(enc>=0&&b1>=0);
  // A damaging first hit could trigger Emergency Exit and force an
  // opponent switch, making the next scripted move choice illegal.
  // Real first-turn Encore precedes the target's first Swords Dance and
  // thus fails; on turn two, the observed Swords Dance can be Encored.
  b.makeChoices('move '+(enc+1),'move '+(b1+1));
  assert.equal(b.requestState,'move','No forced replacement in setup test');
  b.makeChoices('move '+(enc+1),'move '+(b1+1));
  logs=b.log.join('\n');
  assert.ok(logs.includes('|-start|p2a:')&&logs.includes('|Encore'),
   'Actual Showdown engine must visibly start Encore on opponent; no fabricated log');
  // Use the request generated by the SAME actual battle, never a hand-made
  // request that accidentally grants impossible moves or extra information.
  // Side.getRequestData() returns only the side's pokemon list;
  // the actual legal move request is Side.activeRequest from Battle.makeRequest.
  const request=b.p1.activeRequest;
  assert.ok(request.active?.[0]?.moves?.length, 'Real battle side must expose move request');
  const savedRequest=structuredClone(request);
  // Saved while the Battle object is alive; requests carry only own-side info.
  capturedRequest=savedRequest;
 }finally{b.destroy();}
 // These are genuine public battle log lines captured from the pinned
 // engine; Bot.run is used strictly as a log observer (no fake requests).
 const reader=async function*(){yield logs;};
 const trace={selections:[],choices:[],errors:[],immuneObservations:[],engineAdvices:[]};
 const v4=new Bot(reader(),sim.Dex.mod('champions'),own,'p1',trace,null,null,{
  decisionPolicy:'v4-public-status'
 });
 await v4.run();
 assert.equal(v4.foeEncoreActive,true);
 const old=new Bot(reader(),sim.Dex.mod('champions'),own,'p1',trace,null,null,{
  decisionPolicy:'v3-public-immunity'
 });
 await old.run();
 assert.equal(old.foeEncoreActive,false,'Baseline policy stays unchanged for paired experiment');
 const oldChoice=old.decide(capturedRequest);
 const newChoice=v4.decide(capturedRequest);
 const moveName=choice=>{
  const index=Number(String(choice).match(/^move (\d+)/)?.[1]);
  return index>0?capturedRequest.active[0].moves[index-1]?.id||'':'non-move';
 };
 assert.equal(moveName(oldChoice),'encore',
  'Old heuristic should reproduce repeat Encore against already Encored +4 Golisopod');
 assert.notEqual(moveName(newChoice),'encore',
  'Only opt-in v4 should use public lock to avoid redundant Encore');
});

test('actual M-C own Encore lock escapes inert Will-O-Wisp only when a safe bench exists',async()=>{
 const sim=load(),own=reportedLive();
 const b=makeThreeBattle(sim,own,reportedLive(),{
  ownThree:['Rotom-Wash','Primarina','Hydreigon'],
  foeThree:['Primarina','Metagross','Hydreigon'],
  seed:[2026,10,29,77]
 });
 let logs,request;
 try{
  const move=(side,id)=>side.active[0].moveSlots.findIndex(x=>x.id===id)+1;
  const wis=move(b.p1,'willowisp'),enc=move(b.p2,'encore');
  assert.ok(wis>0&&enc>0);
  b.makeChoices('move '+wis,'move '+enc);
  logs=b.log.join('\n');
  request=structuredClone(b.p1.activeRequest);
  assert.ok(logs.includes('|-start|p1a:')&&logs.includes('|Encore'),
   'We must be locked by the REAL Showdown Encore public event');
  assert.ok(logs.includes('|-status|p2a:')&&logs.includes('|brn'),
   'Opponent is already burned, proving locked Will-O-Wisp would be inert');
  assert.equal(request.active[0].moves.filter(m=>!m.disabled&&m.pp>0).length,1,
   'Actual M-C request restricts the Encore-locked move');
 }finally{b.destroy();}
 async function bot(policy){
  const trace={selections:[],choices:[],errors:[],immuneObservations:[],engineAdvices:[],lockEscapes:[]};
  const stream=(async function*(){yield logs;})();
  const ai=new Bot(stream,sim.Dex.mod('champions'),own,'p1',trace,null,null,
   {decisionPolicy:policy});
  await ai.run();
  return {choice:ai.decide(request),trace,ownEncoreActive:ai.ownEncoreActive};
 }
 const old=await bot('v3-public-immunity');
 const improved=await bot('v4-public-status');
 assert.equal(old.choice,'move 4','Old policy reproduces the real ineffective locked move');
 assert.equal(improved.ownEncoreActive,true);
 assert.match(improved.choice,/^switch [1-6]$/,
  'v4 must escape when the opponent is already burned AND a safer bench exists');
 assert.equal(improved.trace.lockEscapes.length,1);
 assert.equal(improved.trace.lockEscapes[0].reason,'public-encore-inert-move');
});
