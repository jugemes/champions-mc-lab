test('real pinned Showdown Encore public event toggles ONLY v4 status tracking',async()=>{
 const sim=load();
 const own=reportedLive(),foe=groups.find(x=>x.name==='01_M7_golisopod_balance').team;
 const b=makeThreeBattle(sim,own,foe,{
  ownThree:['Primarina','Metagross','Hydreigon'],
  foeThree:['Golisopod','Mimikyu','Garchomp'],
  seed:[2026,10,29,55]
 });
 let logs,capturedRequest;
 try{
  const enc=b.p1.active[0].moveSlots.findIndex(x=>x.id==='encore');
  const b1=b.p2.active[0].moveSlots.findIndex(x=>x.id==='swordsdance');
  assert.ok(enc>=0&&b1>=0);
  // A damaging first hit could trigger Emergency Exit and force an
  // opponent switch, making the next scripted move choice illegal.
  // Real first-turn Encore precedes the target's first Swords Dance and
  // thus fails; on turn two, the observed Swords Dance can be Encored.
  b.makeChoices('move '+(enc+1),'move '+(b1+1));
  assert.equal(b.requestState,'move','No forced replacement in setup test');
  b.makeChoices('move '+(enc+1),'move '+(b1+1));
  logs=b.log.join('\n');
  assert.ok(logs.includes('|-start|p2a:')&&logs.includes('|Encore'),
   'Actual Showdown engine must visibly start Encore on opponent; no fabricated log');
  // Use the request generated by the SAME actual battle, never a hand-made
  // request that accidentally grants impossible moves or extra information.
  // Side.getRequestData() returns only the side's pokemon list;
  // the actual legal move request is Side.activeRequest from Battle.makeRequest.
  const request=b.p1.activeRequest;
  assert.ok(request.active?.[0]?.moves?.length, 'Real battle side must expose move request');
  const savedRequest=structuredClone(request);
  // Saved while the Battle object is alive; requests carry only own-side info.
  capturedRequest=savedRequest;
 }finally{b.destroy();}
 // These are genuine public battle log lines captured from the pinned
 // engine; Bot.run is used strictly as a log observer (no fake requests).
 const reader=async function*(){yield logs;};
 const trace={selections:[],choices:[],errors:[],immuneObservations:[],engineAdvices:[]};
 const v4=new Bot(reader(),sim.Dex.mod('champions'),own,'p1',trace,null,null,{
  decisionPolicy:'v4-public-status'
 });
 await v4.run();
 assert.equal(v4.foeEncoreActive,true);
 const old=new Bot(reader(),sim.Dex.mod('champions'),own,'p1',trace,null,null,{
  decisionPolicy:'v3-public-immunity'
 });
 await old.run();
 assert.equal(old.foeEncoreActive,false,'Baseline policy stays unchanged for paired experiment');
 const oldChoice=old.decide(capturedRequest);
 const newChoice=v4.decide(capturedRequest);
 const moveName=choice=>{
  const index=Number(String(choice).match(/^move (\d+)/)?.[1]);
  return index>0?capturedRequest.active[0].moves[index-1]?.id||'':'non-move';
 };
 assert.equal(moveName(oldChoice),'encore',
  'Old heuristic should reproduce repeat Encore against already Encored +4 Golisopod');
 assert.notEqual(moveName(newChoice),'encore',
  'Only opt-in v4 should use public lock to avoid redundant Encore');
});

test('actual M-C own Encore lock escapes inert Will-O-Wisp only when a safe bench exists',async()=>{
 const sim=load(),own=reportedLive();
 const b=makeThreeBattle(sim,own,reportedLive(),{
  ownThree:['Rotom-Wash','Primarina','Hydreigon'],
  foeThree:['Primarina','Metagross','Hydreigon'],
  seed:[2026,10,29,77]
 });
 let logs,request;
 try{
  const move=(side,id)=>side.active[0].moveSlots.findIndex(x=>x.id===id)+1;
  const wis=move(b.p1,'willowisp'),enc=move(b.p2,'encore');
  assert.ok(wis>0&&enc>0);
  b.makeChoices('move '+wis,'move '+enc);
  logs=b.log.join('\n');
  request=structuredClone(b.p1.activeRequest);
  assert.ok(logs.includes('|-start|p1a:')&&logs.includes('|Encore'),
   'We must be locked by the REAL Showdown Encore public event');
  assert.ok(logs.includes('|-status|p2a:')&&logs.includes('|brn'),
   'Opponent is already burned, proving locked Will-O-Wisp would be inert');
  assert.equal(request.active[0].moves.filter(m=>!m.disabled&&m.pp>0).length,1,
   'Actual M-C request restricts the Encore-locked move');
 }finally{b.destroy();}
 async function bot(policy){
  const trace={selections:[],choices:[],errors:[],immuneObservations:[],engineAdvices:[],lockEscapes:[]};
  const stream=(async function*(){yield logs;})();
  const ai=new Bot(stream,sim.Dex.mod('champions'),own,'p1',trace,null,null,
   {decisionPolicy:policy});
  await ai.run();
  return {choice:ai.decide(request),trace,ownEncoreActive:ai.ownEncoreActive,ai};
 }
 const old=await bot('v3-public-immunity');
 const improved=await bot('v4-public-status');
 assert.equal(old.choice,'move 4','Old policy reproduces the real ineffective locked move');
 assert.equal(improved.ownEncoreActive,true);
 // Diagnostic gate: record why the real request did or did not permit an
 // escape before declaring the behaviour corrected. A policy that stays in
 // because the only bench is dangerous must not be forced to switch blindly.
 const view=improved.ai;
 const side=request.side.pokemon;
 const curr=side.find(p=>p.active);
 const my=view.activeView(curr,request.active[0]).my;
 const observed={foe:view.foeActive,foeStatus:view.foeStatus,
  ownEncore:view.ownEncoreActive,
  trapped:Boolean(request.active[0].trapped),
  maybeTrapped:Boolean(request.active[0].maybeTrapped),
  canSwitch:canSwitchAgainst(view.dex,request.active[0],my,view.foeActive,view.foeAbility),
  switchCount:view.switches,
  currentRisk:incomingRisk(view.dex,my,view.foeActive,{foeBoosts:view.foeBoosts,seenMoves:view.seenMoves[view.foeActive]}),
  bench:side.filter(p=>!p.active&&!String(p.condition).endsWith(' fnt')).map(p=>({
   pokemon:view.getSet(p).species,
   risk:incomingRisk(view.dex,view.getSet(p),view.foeActive,{foeBoosts:view.foeBoosts,seenMoves:view.seenMoves[view.foeActive]})
  })),choice:improved.choice};
 console.log('P0_LOCK_ESCAPES_DIAGNOSTIC '+JSON.stringify(observed));
 assert.ok(improved.choice==='move 4'||/^switch [1-6]$/.test(improved.choice),
  'A legal move or switch must be chosen, not a fabricated choice');
 assert.equal(observed.canSwitch,true,'The server permits legal voluntary switches here');
 const viable=observed.bench.find(x=>x.pokemon==='Primarina');
 assert.ok(viable&&viable.risk<observed.currentRisk,
  'Primarina has lower public-STAB risk than an inertly locked Rotom');
 const switched=Number(improved.choice.match(/^switch (\d+)$/)?.[1]);
 assert.ok(switched>0,'Escape the inert Encore lock to a survivable lower-risk bench');
 assert.equal(request.side.pokemon[switched-1].details.split(',')[0],'Primarina',
  'Do not pivot to a Fairy-weak Hydreigon');
 assert.equal(improved.trace.lockEscapes.length,1);
 assert.equal(improved.trace.lockEscapes[0].reason,'public-encore-inert-move');
});

test('v4 own Encore policy escapes to a real safer Toxapex bench, v3 wastes the turn',async()=>{
 const sim=load(),foe=reportedLive(),team=structuredClone(reportedLive());
 const pex=structuredClone(archetypes.stall.find(p=>p.species==='Toxapex'));
 team[team.findIndex(p=>p.species==='Hydreigon')]=pex;
 const b=makeThreeBattle(sim,team,foe,{
  ownThree:['Rotom-Wash','Primarina','Toxapex'],
  foeThree:['Primarina','Metagross','Hydreigon'],
  seed:[2026,10,29,77]
 });
 try{
  const slot=(side,id)=>{
   const i=side.active[0].moveSlots.findIndex(m=>m.id===id);
   assert.ok(i>=0,'required scripted move is legal: '+id);
   return i+1;
  };
  b.makeChoices('move '+slot(b.p1,'willowisp'),
    'move '+slot(b.p2,'encore'));
  const request=structuredClone(b.p1.activeRequest);
  const logs=b.log.join('\n');
  async function decide(policy){
   const trace={selections:[],choices:[],errors:[],lockEscapes:[]};
   const bot=new Bot((async function*(){yield logs;})(),
    sim.Dex.mod('champions'),team,'p1',trace,null,null,{decisionPolicy:policy});
   await bot.run();
   const choice=bot.decide(request);
   return {choice,trace};
  }
  const old=await decide('v3-public-immunity');
  const improved=await decide('v4-public-status');
  assert.equal(old.choice,'move 4','Baseline still repeats Encore-locked burn');
  const switched=Number(improved.choice.match(/^switch (\d+)$/)?.[1]);
  assert.ok(switched>0,'v4 must escape to an actually safer bench');
  assert.equal(request.side.pokemon[switched-1].details.split(',')[0],'Toxapex',
   'Rational escape goes to a Water/Fairy-resistant Toxapex, not a vulnerable Dragon');
  assert.equal(improved.trace.lockEscapes.length,1);
  assert.equal(improved.trace.lockEscapes[0].reason,'public-encore-inert-move');
  // Unlike a fabricated request, this is a real legal M-C next turn.
  b.makeChoices(improved.choice,'move '+slot(b.p2,'moonblast'));
  assert.equal(b.p1.active[0].species.name,'Toxapex',
    'The full Showdown engine accepted and executed the AI-selected switch');
 }finally{b.destroy();}
});

test('Claude counterexample: two Moonblast turns, inert lock stay vs Primarina escape in actual M-C battle',()=>{
 const sim=load(),ours=reportedLive(),enemy=reportedLive();
 const run=escape=>{
  const battle=makeThreeBattle(sim,ours,enemy,{
   ownThree:['Rotom-Wash','Primarina','Hydreigon'],
   foeThree:['Primarina','Metagross','Hydreigon'],seed:[2026,10,29,77]
  });
  const command=(side,name)=>{
   const i=side.active[0].moveSlots.findIndex(x=>x.id===sim.Dex.moves.get(name).id);
   assert.ok(i>=0,'Must have real move '+name);
   return 'move '+(i+1);
  };
  try{
   battle.makeChoices(command(battle.p1,'Will-O-Wisp'),command(battle.p2,'Encore'));
   assert.ok(battle.log.some(x=>x.includes('|-start|p1a:')&&x.includes('|Encore')));
   const second=escape?'switch 2':command(battle.p1,'Will-O-Wisp');
   battle.makeChoices(second,command(battle.p2,'Moonblast'));
   if(!battle.ended&&battle.requestState==='move'){
    battle.makeChoices(command(battle.p1,escape?'Sparkling Aria':'Will-O-Wisp'),
      command(battle.p2,'Moonblast'));
   }
   const rot=battle.p1.pokemon.find(x=>x.species.name==='Rotom-Wash');
   const pri=battle.p1.pokemon.find(x=>x.species.name==='Primarina');
   return {rotHP:rot.hp,rotFaint:rot.fainted,priHP:pri.hp};
  }finally{battle.destroy();}
 };
 const stays=run(false),escapes=run(true);
 assert.equal(stays.rotFaint,true,'Repeating a nonfunctional burn loses Rotom to two Moonblasts');
 assert.equal(escapes.rotFaint,false,'Switch preserves Rotom in the same enemy line');
 assert.ok(escapes.priHP>0,'The switched-in Primarina survives the two-turn battle');
});
